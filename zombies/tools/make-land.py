# Turns the squares read off art/map.svg (tools/read-map.py) into the LAND
# picture in data/map.js: closes diagonal gaps in the stream, marks bridges.
g = """.................BB.................
.................BB.................
.................BB.......~.........
....~~~~.........BB......~~~..##....
...~~~~.~........BB......~~..###....
...~~~~~~........BB......BB..####...
...~~~.~.........BB......~~....#....
.....~~...........B.......~~........
..................B.......~~~.......
.................BB.......~~........
.................BB.....~~~.........
B.BBBBBBBBBBBBBBBBBB....~~..........
................BBBB....~~~.........
.........................~~~~.......
...........................~~.......
...#.###...................~~~......
...#######...............~~~~.......
...########..............~~~........
..########.#.............BB.........
..#########..............~~.........
...####.####..............~~........
..........................~.........
....................................
....................................""".split('\n')
W, H = 36, 24
grid = [list(r) for r in g]
BRIDGE_ROWS = {5, 18}
# the stream: columns of water (and bridge) per row, east of col 20
stream = {}
for r in range(H):
    cols = [c for c in range(20, W) if grid[r][c] in '~B']
    if cols: stream[r] = cols
stream[0] = stream[1] = [26, 27]
stream[22] = stream[23] = [26, 27]
stream[21] = [26, 27]
# close diagonal gaps: each row covers its own span joined to the next row's
out = [['.' for _ in range(W)] for _ in range(H)]
for r in range(H):
    for c in range(W):
        ch = grid[r][c]
        if ch == '#': out[r][c] = '#'
        elif ch == '~' and c < 15: out[r][c] = 'o'
        elif ch == 'B' and c < 22: out[r][c] = ':'
for r in range(H):
    span = set(stream[r])
    if r + 1 < H and r not in BRIDGE_ROWS and (r + 1) not in BRIDGE_ROWS: span |= set(stream[r + 1])
    lo, hi = min(span), max(span)
    for c in range(lo, hi + 1): out[r][c] = '=' if r in BRIDGE_ROWS else '~'
# bridges should not leave a water square either side
for r in BRIDGE_ROWS:
    for c in range(20, W):
        if out[r][c] == '~': out[r][c] = '='
for r in range(H): print("  '" + ''.join(out[r]) + "',")
